"""Speech-to-Text engine, from scratch.

Recognizes isolated words from a known vocabulary. Recognition templates are
generated by this project's own from-scratch TTS (zero external model data),
and users can enroll their own voice per word for speaker-dependent accuracy.

Pipeline: load/resample audio -> energy VAD -> energy-valley word
segmentation -> MFCC features -> banded DTW against vocabulary templates ->
margin-based scoring with unknown-word rejection.

Limitations (honest, inherent to a from-scratch engine): connected fluent
speech, large vocabularies, and heavy noise are out of reach without a
trained acoustic model. Speak with small pauses between words; enroll your
own voice for best accuracy.
"""
import os
import tempfile

import numpy as np

from .dtw import dtw_cost, INF
from .features import MFCCExtractor
from .tts import TextToSpeech, load_wav, resample, save_wav

DEFAULT_VOCABULARY = [
    "hello", "hi", "hey", "yes", "no", "okay", "stop", "start",
    "help", "goodbye", "thanks", "please", "sorry", "open",
    "close", "exit", "time", "weather", "music", "name",
    "one", "two", "three", "four", "five",
]


class SpeechRecognizer:
    def __init__(self, vocabulary=None, sample_rate=16000,
                 unknown_threshold=0.82, margin_ratio=0.82,
                 n_cepstra=19, template_tts=None):
        self.sample_rate = sample_rate
        self.unknown_threshold = unknown_threshold
        self.margin_ratio = margin_ratio
        self.extractor = MFCCExtractor(sample_rate=sample_rate,
                                       n_cepstra=n_cepstra)
        self.tts = template_tts or TextToSpeech()
        self.templates = {}
        self._template_durations = {}
        self._feat_scale = np.ones(self.extractor.n_cepstra)
        self.build_vocabulary(vocabulary or DEFAULT_VOCABULARY)

    # ------------------------------------------------------------ templates
    def build_vocabulary(self, words):
        """Synthesize reference features for each vocabulary word with the
        built-in TTS (no external model data involved). Variants cover
        speaking rate, pitch, tempo warps, and light additive noise so
        recognition tolerates natural delivery variation."""
        for word in words:
            word = word.lower().strip()
            if not word or word in self.templates:
                continue
            variants = []
            base_rate = self.tts.rate
            base_f0 = self.tts.synth.base_f0
            for rate in (0.85, 1.0, 1.2):
                for pitch in (1.0, 1.12):
                    self.tts.rate = base_rate * rate
                    self.tts.synth.base_f0 = base_f0 * pitch
                    audio = self.tts.synthesize(word)
                    if len(audio) == 0:
                        continue
                    audio16 = resample(audio, self.tts.sample_rate,
                                       self.sample_rate)
                    ceps, _ = self.extractor.extract(audio16)
                    variants.append(ceps)
                    if rate == 1.0 and pitch == 1.0:
                        self._template_durations[word] = \
                            len(audio16) / self.sample_rate
                        variants.append(self._time_warp(ceps, 0.85))
                        variants.append(self._time_warp(ceps, 1.18))
                        for speed in (0.85, 1.176):
                            idx = np.arange(0.0, len(audio16), speed)
                            tape = np.interp(idx, np.arange(len(audio16)),
                                             audio16)
                            tape_ceps, _ = self.extractor.extract(tape)
                            variants.append(tape_ceps)
                    if rate == 1.0:
                        rng = np.random.default_rng(
                            len(ceps) + len(word) * 131)
                        noisy = audio16 + rng.normal(
                            0.0, 0.08 * float(np.abs(audio16).max() + 1e-9),
                            len(audio16))
                        noisy_ceps, _ = self.extractor.extract(noisy)
                        variants.append(noisy_ceps)
            self.tts.rate = base_rate
            self.tts.synth.base_f0 = base_f0
            if variants:
                self.templates[word] = variants
        self._update_feature_scale()

    def _time_warp(self, cepstra, factor):
        """Feature-domain time stretch of a template (tempo variation)."""
        n_in = len(cepstra)
        idx = np.linspace(0, n_in - 1, max(4, int(round(n_in * factor))))
        out = np.empty((len(idx), cepstra.shape[1]), dtype=cepstra.dtype)
        for c in range(cepstra.shape[1]):
            out[:, c] = np.interp(idx, np.arange(n_in), cepstra[:, c])
        return out

    def _update_feature_scale(self):
        pooled = np.vstack([t if isinstance(t, np.ndarray) else np.vstack(t)
                            for t in self.templates.values()]) \
            if self.templates else None
        if pooled is not None and len(pooled) > 4:
            self._feat_scale = np.maximum(pooled.std(axis=0), 1e-6)

    def _prep(self, cepstra, mean=None):
        return cepstra

    def enroll(self, word, samples, sample_rate=None):
        """Add the user's own recording of a word to its template set."""
        word = word.lower().strip()
        if sample_rate is not None:
            samples = resample(samples, sample_rate, self.sample_rate)
        ceps, _ = self.extractor.extract(samples)
        self.templates.setdefault(word, [])
        if isinstance(self.templates[word], list):
            self.templates[word].append(self._prep(ceps))
        else:
            self.templates[word] = [self.templates[word], self._prep(ceps)]

    def enroll_file(self, word, path):
        samples, sr = load_wav(path)
        self.enroll(word, samples, sr)

    # ------------------------------------------------------------ decoding
    def transcribe(self, source, sample_rate=None):
        """Transcribe a WAV path or a float array. Returns a result dict:
        {text, words: [{word, start, end, confidence}], duration, engine}."""
        if isinstance(source, str):
            if not os.path.exists(source):
                raise FileNotFoundError(source)
            samples, sr = load_wav(source)
        else:
            samples = np.asarray(source, dtype=np.float64)
            sr = sample_rate or self.sample_rate
        duration = len(samples) / sr

        if sr != self.sample_rate:
            samples = resample(samples, sr, self.sample_rate)
        if len(samples) < self.extractor.frame_len:
            return {"text": "", "words": [], "duration": duration,
                    "engine": "natural_speech"}

        ceps, energy = self.extractor.extract(samples)
        utterance_mean = ceps.mean(axis=0, keepdims=True)

        def prep(seg_ceps):
            return self._prep(seg_ceps, mean=utterance_mean)

        decoded = []
        for seg in self._word_segments(energy):
            a, b = self._trim_edges(energy, seg[0], seg[1])
            if b - a < 4:
                continue
            decoded.extend(self._decode(ceps, energy, a, b, depth=0))
        words = []
        for f0f, f1f, best_word, best_cost, second_cost in decoded:
            start_t = f0f * self.extractor.hop / self.sample_rate
            end_t = f1f * self.extractor.hop / self.sample_rate
            if best_word is None or best_cost > self.unknown_threshold:
                words.append({"word": "<unk>", "start": start_t,
                              "end": end_t, "confidence": 0.0,
                              "closest": best_word})
                continue
            if second_cost < INF and best_cost > second_cost * \
                    self.margin_ratio:
                confidence = 0.35
            else:
                gap = (second_cost - best_cost) / max(second_cost, 1e-6)
                confidence = float(min(1.0, max(0.3, 1.0 - best_cost /
                                                self.unknown_threshold *
                                                0.45 + gap * 0.35)))
            words.append({"word": best_word, "start": start_t,
                          "end": end_t, "confidence": round(confidence, 3)})
        text = " ".join(w["word"] for w in words if w["word"] != "<unk>")
        return {"text": text, "words": words, "duration": round(duration, 3),
                "engine": "natural_speech"}

    def record(self, seconds, device_index=None):
        """Record from the microphone if pyaudio is installed."""
        try:
            import pyaudio
        except ImportError as exc:
            raise RuntimeError(
                "Microphone capture needs pyaudio; otherwise pass a WAV "
                "file or numpy array to transcribe().") from exc
        chunk = 1024
        pa = pyaudio.PyAudio()
        stream = pa.open(format=pyaudio.paFloat32, channels=1,
                         rate=self.sample_rate, input=True,
                         input_device_index=device_index,
                         frames_per_buffer=chunk)
        frames = []
        for _ in range(int(self.sample_rate / chunk * seconds)):
            frames.append(np.frombuffer(stream.read(chunk),
                                        dtype=np.float32))
        stream.stop_stream()
        stream.close()
        pa.terminate()
        return np.concatenate(frames).astype(np.float64)

    def record_to_file(self, seconds, path):
        audio = self.record(seconds)
        save_wav(path, audio, self.sample_rate)
        return path

    # ------------------------------------------------------------ internals
    def _word_segments(self, energy):
        """Split frame energies into word segments using energy valleys.

        Energy is smoothed and gate gaps are bridged liberally: intra-word
        stop closures must not split a word (multi-word runs are separated
        later by the recursive DTW splitter, not the VAD)."""
        kernel = np.ones(5) / 5.0
        smooth = np.convolve(energy, kernel, mode="same")
        peak = np.percentile(smooth, 95)
        floor = np.percentile(smooth, 10)
        if peak - floor < 1e-6:
            return []
        thr = floor + 0.15 * (peak - floor)
        voiced = smooth > thr

        return self._runs(voiced, min_len=5, min_gap=12)

    @staticmethod
    def _runs(mask, min_len=5, min_gap=3):
        idx = np.flatnonzero(mask)
        if len(idx) == 0:
            return []
        runs = []
        start = idx[0]
        prev = idx[0]
        for i in idx[1:]:
            if i - prev > min_gap:
                if prev - start + 1 >= min_len:
                    runs.append((start, prev + 1))
                start = i
            prev = i
        if prev - start + 1 >= min_len:
            runs.append((start, prev + 1))
        return runs

    @staticmethod
    def _trim_edges(energy, a, b, rel=0.0):
        """Trim low-energy frames at the edges of a segment (rel <= 0: keep
        everything; soft onsets like /h/ and /s/ carry distinctive cues)."""
        if rel <= 0.0 or b - a < 8:
            return int(a), int(b)
        seg = energy[a:b]
        peak = float(np.percentile(seg, 95))
        floor = float(np.percentile(seg, 10))
        if peak - floor < 1e-6:
            return int(a), int(b)
        cut = floor + rel * (peak - floor)
        lo = 0
        while lo < len(seg) and seg[lo] < cut:
            lo += 1
        hi = len(seg)
        while hi > lo + 4 and seg[hi - 1] < cut:
            hi -= 1
        return int(a + lo), int(a + hi)

    def _match(self, seg_feats):
        results = []
        for word, tpl in self.templates.items():
            tpls = tpl if isinstance(tpl, list) else [tpl]
            best = INF
            for t in tpls:
                band = max(30, abs(len(seg_feats) - len(t)) + 12)
                c = dtw_cost(seg_feats, t, band=band)
                best = min(best, c)
            results.append((word, best))
        results.sort(key=lambda x: x[1])
        if not results:
            return None, INF, INF
        best_word, best_cost = results[0]
        second = results[1][1] if len(results) > 1 else INF
        return best_word, best_cost, second

    def _template_frames(self, word):
        dur = self._template_durations.get(word, 0.30)
        return max(6.0, dur * self.sample_rate / self.extractor.hop)

    def _decode(self, feats, energy, a, b, depth=0):
        """Decode one utterance into a sequence of words. If the segment is
        much longer than its best template, attempt a 2-way split at the
        position whose left+right DTW costs beat matching the whole thing.
        Segment edges are trimmed of low-energy frames at every level."""
        a, b = self._trim_edges(energy, a, b)
        if b - a < 4:
            return []
        seg = self._prep(feats[a:b])
        word, cost, second = self._match(seg)
        n_frames = b - a
        if word is None or n_frames <= 4:
            return [(a, b, word, cost, second)]
        if n_frames <= self._template_frames(word) * 1.30 or depth >= 3:
            return [(a, b, word, cost, second)]
        lo = a + max(4, int(n_frames * 0.15))
        hi = a + int(n_frames * 0.85)
        best_split = None
        for p in range(lo, hi + 1, 2):
            if p - a < 4 or b - p < 4:
                continue
            lw, lc, _ = self._match(self._prep(feats[a:p]))
            rw, rc, _ = self._match(self._prep(feats[p:b]))
            if lw is None or rw is None:
                continue
            total = lc + rc
            if best_split is None or total < best_split[0]:
                best_split = (total, p, lw, lc, rw, rc)
        if best_split is not None and best_split[0] / 2.0 < cost * 0.97:
            p = best_split[1]
            return (self._decode(feats, energy, a, p, depth + 1) +
                    self._decode(feats, energy, p, b, depth + 1))
        return [(a, b, word, cost, second)]


def quick_transcribe(path, vocabulary=None, **kwargs):
    recognizer = SpeechRecognizer(vocabulary=vocabulary, **kwargs)
    return recognizer.transcribe(path)


def demo_command_loop(seconds_per_command=2.0, vocabulary=None):
    """Interactive microphone demo (requires pyaudio). Ctrl+C in terminal
    ends the loop."""
    recognizer = SpeechRecognizer(vocabulary=vocabulary)
    print("natural_speech command loop — speak one word at a time. Ctrl+C to exit.")
    while True:
        try:
            path = recognizer.record_to_file(
                seconds_per_command,
                os.path.join(tempfile.gettempdir(), "aira_cmd.wav"))
            result = recognizer.transcribe(path)
            if result["text"]:
                print(f"heard: {result['text']}")
            else:
                print("(silence)")
        except KeyboardInterrupt:
            print("\nbye!")
            break
